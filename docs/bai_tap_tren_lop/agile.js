/**
 * AGILE LÀ GÌ?
 * Agile là phương pháp phát triển phần mềm linh hoạt, tập trung vào việc cung cấp giá trị nhanh chóng
 * và liên tục cho khách hàng thông qua các vòng lặp phát triển ngắn (Iterations / Sprints).
 * Agile nhấn mạnh sự hợp tác, phản hồi liên tục và khả năng thích ứng linh hoạt với thay đổi
 * trong suốt quá trình phát triển phần mềm.
 *
 * Tập trung vào việc chia nhỏ dự án thành nhiều giai đoạn ngắn, liên tục xây dựng sản phẩm,
 * kiểm thử, nhận phản hồi và cải tiến.
 * Agile giúp nhóm phát triển phần mềm làm việc hiệu quả hơn, tăng tính linh hoạt và đáp ứng
 * nhanh chóng với yêu cầu thay đổi từ khách hàng.
 *
 * SO SÁNH WATERFALL VS AGILE:
 * - Waterfall (Thác nước): Phân tích toàn bộ -> Thiết kế toàn bộ -> Lập trình toàn bộ -> Kiểm thử -> Bàn giao.
 * - Agile (Linh hoạt): Phân tích một phần -> Thiết kế -> Lập trình -> Kiểm thử -> Nhận phản hồi -> Tiếp tục phần tiếp theo.
 *
 * Điểm quan trọng nhất của Agile là KHÔNG đợi đến khi hoàn thành toàn bộ dự án mới đưa sản phẩm
 * cho khách hàng sử dụng và đánh giá.
 *
 * VÌ SAO CẦN AGILE?
 * Hãy tưởng tượng nhà trường đặt hàng sinh viên xây dựng một website quản lý điểm rèn luyện:
 * - Nếu sử dụng Waterfall: Nhóm sinh viên có thể mất 4 tháng để hoàn thành toàn bộ hệ thống rồi mới trình bày cho khách hàng.
 *   Nhưng có một vấn đề: Đến tháng thứ 4, khách hàng mới phát hiện giao diện, quy trình chấm điểm và cách tính điểm
 *   không đúng nhu cầu thực tế. Khi đó, nhóm sinh viên sẽ phải sửa lại toàn bộ hệ thống, mất rất nhiều thời gian và công sức.
 * - Nếu sử dụng Agile: Nhóm sinh viên sẽ chia dự án thành nhiều phần nhỏ (Mỗi phần gọi là 1 Sprint, kéo dài 1 - 2 tuần).
 *   Mỗi phần sẽ được phát triển, kiểm thử và trình bày ngay cho khách hàng xem thử và lấy ý kiến góp ý tức thì.
 *
 * -------------------------------------------------------------
 * 4 GIÁ TRỊ CỐT LÕI CỦA AGILE (Agile Manifesto):
 * -------------------------------------------------------------
 * 1. Cá nhân và sự tương tác HƠN LÀ quy trình và công cụ.
 * 2. Phần mềm hoạt động tốt HƠN LÀ tài liệu đầy đủ, cồng kềnh.
 * 3. Hợp tác với khách hàng HƠN LÀ đàm phán hợp đồng cứng nhắc.
 * 4. Phản hồi với sự thay đổi HƠN LÀ bám sát theo kế hoạch cố định.
 *
 * -------------------------------------------------------------
 * 12 NGUYÊN TẮC CỦA AGILE (12 Agile Principles):
 * -------------------------------------------------------------
 * 1. Ưu tiên cao nhất là làm hài lòng khách hàng thông qua việc bàn giao phần mềm có giá trị sớm và liên tục.
 * 2. Chào đón các yêu cầu thay đổi, ngay cả trong giai đoạn muộn của quá trình phát triển.
 * 3. Bàn giao phần mềm hoạt động thường xuyên, từ vài tuần đến vài tháng, ưu tiên khoảng thời gian ngắn hơn.
 * 4. Các nhà kinh doanh và các nhà phát triển phải làm việc cùng nhau hàng ngày trong suốt dự án.
 * 5. Xây dựng các dự án xung quanh các cá nhân có động lực. Cung cấp môi trường và hỗ trợ cần thiết, đồng thời tin tưởng họ để hoàn thành công việc.
 * 6. Phương pháp hiệu quả và năng suất nhất để truyền đạt thông tin trong nhóm phát triển là trò chuyện trực tiếp (Face-to-face).
 * 7. Phần mềm hoạt động tốt là thước đo chính của tiến độ dự án.
 * 8. Các quy trình Agile thúc đẩy sự phát triển bền vững. Các nhà tài trợ, nhà phát triển và người dùng cần duy trì nhịp độ làm việc ổn định lâu dài.
 * 9. Liên tục chú ý đến kỹ thuật xuất sắc và thiết kế tốt để tăng cường tính linh hoạt.
 * 10. Sự đơn giản – nghệ thuật tối đa hóa lượng công việc chưa cần làm – là điều cốt yếu.
 * 11. Các kiến trúc, yêu cầu và thiết kế tốt nhất xuất hiện từ các nhóm tự tổ chức (Self-organizing teams).
 * 12. Định kỳ đều đặn, nhóm phát triển suy ngẫm về cách làm việc hiệu quả hơn, sau đó điều chỉnh và tinh chỉnh hành vi của mình cho phù hợp (Sprint Retrospective).
 */
